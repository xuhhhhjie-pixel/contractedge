import tempfile,unittest
from pathlib import Path
from contractedge.source.snapshot import compute_snapshot
from contractedge.source.units import extract_units

class ProbeEntryEvidenceTests(unittest.TestCase):
 def test_focused_public_entry_keeps_relevant_sibling_bodies_in_pool(self):
  with tempfile.TemporaryDirectory() as td:
   root=Path(td);(root/'api.go').write_text('package p\nfunc mutator() { Select(configPath); Run(configPath) }\nfunc validator() { Select(configPath); Run(configPath) }\n')
   docs=[]
   for i in range(12):
    p=root/f'doc{i}.txt';p.write_text('public documentation for configPath\n');docs.append(p.name)
   snap=compute_snapshot(root)
   units=extract_units(snap,{'seed_paths':docs+['api.go']},query='Use `configPath`',max_units=8,focused_paths=['api.go'])
   self.assertTrue({'mutator','validator'}<={u.get('symbol') for u in units})
   self.assertLessEqual(len(units),8)
 def test_locator_uses_only_registered_package_api_and_reports_limits(self):
  from contractedge.source.entrypoints import probe_entrypoint_hints
  with tempfile.TemporaryDirectory() as td:
   root=Path(td);(root/'pkg').mkdir();(root/'other').mkdir()
   (root/'pkg/api.go').write_text('package p\ntype Renderer struct {}\n')
   (root/'other/api.go').write_text('package q\ntype Renderer struct {}\n')
   snap=compute_snapshot(root);spec=[{'sha256':'a'*64,'api_entrypoints':[{'package':'pkg','symbol':'Renderer'}]}]
   hints,paths,audit=probe_entrypoint_hints(snap,spec)
   self.assertEqual(paths,['pkg/api.go']);self.assertIn('METHOD_PROBE_PUBLIC_API',hints[0]['origin_ref'])
   self.assertEqual(probe_entrypoint_hints(snap,spec,max_files=0)[1],[])
   self.assertTrue(probe_entrypoint_hints(snap,spec,max_files=0)[2]['truncated'])
   with self.assertRaises(ValueError):probe_entrypoint_hints(snap,[{'sha256':'x','api_entrypoints':[{'package':'../private','symbol':'Renderer'}]}])


def test_unregistered_ordering_requirement_keeps_both_sides_of_long_go_handler(tmp_path):
    text = ('package worker\nfunc (w *Worker) Process(RequestToken string, KeyMaterial string) {\n'
        + '// body padding\n'*95 + 'HandleTerminal(RequestToken)\n'
        + '// more padding\n'*35 + 'MatchKeyMaterial(RequestToken, KeyMaterial)\n}\n')
    (tmp_path/'worker.go').write_text(text)
    snapshot=compute_snapshot(tmp_path)
    units=extract_units(snapshot,{'seed_paths':['worker.go']},
        query='Compare RequestToken with current KeyMaterial before handling terminal states')
    complete=[u for u in units if u.get('symbol')=='Process' and not u.get('truncated')]
    assert complete
    assert 'HandleTerminal(RequestToken)' in complete[0]['text']
    assert 'MatchKeyMaterial(RequestToken, KeyMaterial)' in complete[0]['text']
    assert complete[0]['snapshot_id']==snapshot.snapshot_id


def test_ordering_expansion_stays_bounded_and_skips_generated_and_test_code(tmp_path):
    text=('package worker\nfunc Process(RequestToken string, KeyMaterial string) {\n'
          + '// body padding\n'*100+'MatchKeyMaterial(RequestToken, KeyMaterial)\n}\n')
    names=['internal/generated/api.go','generated/api.go','tests/fixture.go','client.go','worker_test.go',*[f'worker{i}.go' for i in range(6)]]
    for name in names:
        p=tmp_path/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(('// Code generated by fixture. DO NOT EDIT.\n' if name=='client.go' else '')+text)
    snapshot=compute_snapshot(tmp_path)
    units=extract_units(snapshot,{'seed_paths':names},max_units=80,
        query='Compare RequestToken with current KeyMaterial before terminal handling')
    grown=[u for u in units if u.get('source_focus_basis','').startswith('BOUNDED_REQUIREMENT_ORDER')]
    assert grown
    assert len({u['path'] for u in grown})<=4
    assert all('generated' not in u['path'] and not u['path'].endswith('_test.go') and u['path'] not in {'tests/fixture.go','client.go'} for u in grown)
    assert all(not u.get('truncated') and len(u['text'])<=32000 for u in grown)
